// P3.9 / W3.9.1-W3.9.6 — the fact catalogue. One row per MB fact.
//
// WHY THIS FILE EXISTS
// --------------------
// brainFactMap says WHICH topic must state a fact. It never says WHAT the fact
// actually asserts. That text lived only in docs/brain/SOURCE-ANALYSIS.md and in
// the Arabic manual, so nothing executable could check a claim, and no reviewer
// could be handed a single sentence to approve or reject.
//
// This module is that missing layer: the literal claim text, its provenance, and
// every number it asserts. src/factRegister.js turns each row into a register
// row (claim_text + trust tier + review cadence), so the shape here is a
// contract. Adding, renaming or dropping a field breaks the register.
//
// WHY EVERY NUMBER NEEDS A ROW (W3.9.2)
// -------------------------------------
// MB module 2 opens with the only rule that matters here: every number is a hard
// fact that must never be invented, approximated, or stated without approved
// evidence. A number with no register row is a number nobody owns, nobody
// re-verifies, and nobody can expire. So `numbers` is exhaustive and literal:
// every numeric literal a claim asserts gets an entry, even when the figure also
// appears in the claim text. 15% is not "roughly the corporate rate", it is a
// rate with an effective date that a reviewer re-checks against the authority.
//
// WHAT THE FIELDS MEAN
// --------------------
// claim          the assertion as REFAL would state it. Plain text, no markdown,
//                no connector dash (anti-regression 0.2). For a fact that is a
//                RULE, the claim states what REFAL does or refuses to do.
// sourceType     who a reviewer must re-verify against. A legal statement that
//                merely arrives via the manual is still cy-authority or
//                foreign-authority, because the manual is not the authority.
// jurisdiction   the country the claim is ABOUT, not where it was written.
// numbers        every numeric literal the claim asserts.
// volatility     starts from the owning topic in brainTaxonomy, overridden per
// trustTier      fact where the fact is clearly different from its topic. Every
//                override carries its reason in `notes`.
// effectiveFrom  only when the source states a date. Never invented.
//
// THE PRICE IS NOT IN HERE. MB-F9 governs the formation package price and
// deliberately carries no figure: MB-DYN6 forbids freezing it, so the value is
// served from refal_offers_and_pricing at runtime (see FORBIDDEN_CORPUS_LITERALS
// in brainFactMap). The same applies to every MB-DYN row.

